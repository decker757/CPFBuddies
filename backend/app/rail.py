"""The whole rail in one process: the demo composition root.

Everything else is deliberately partial. `trustrail.app.create_demo_app` runs
the Mandate Service and Verifier with no agents; `app.main.create_app` runs the
stub marketplace with no rail. This is the only module that imports both, which
is why the wiring nobody else can do — registering merchants and agents,
pointing the Browser Agent at a marketplace, handing the Evaluator its key —
happens here.

In deployment these are separate services and this file is replaced by
configuration. What it encodes that configuration must also encode:

- The Verifier trusts the *address* of whatever key the Mandate Service signs
  with. Wire one and forget the other and every mandate fails its signature.
- The Merchant Registry's payout address is agreed with the platform. The
  marketplace also publishes an address in its listings, and the two being
  equal is what the Verifier checks. Deriving one from the other here would
  make the check vacuous, so both are stated.
- Both of the Evaluator's ids are registered. It reports `evaluator-rules-v1`
  when its model is unreachable and `evaluator-hybrid-nova-v1` when it is not,
  and an unregistered id is a deterministic FAIL.
"""

